/** מפה: מונח מנורמל → כל המונחים השקולים לו (כולל עצמו). */
const SYNONYMS = new Map<string, string[]>();

for (const group of GROUPS) {
  const normalized = [...new Set(group.map(normalize).filter(Boolean))];
  for (const term of normalized) {
    const existing = SYNONYMS.get(term) ?? [];
    // איחוד ולא דריסה — מונח שמופיע בשתי קבוצות מקבל את שתיהן
    SYNONYMS.set(term, [...new Set([...existing, ...normalized])]);
  }
}

/** כל המונחים השקולים למונח נתון. תמיד מכיל את המונח עצמו. */
export function synonymsOf(term: string): string[] {
  return SYNONYMS.get(normalize(term)) ?? [normalize(term)];
}

/** מרחיב רשימת מילים לכל השקילויות שלהן, בלי כפילויות. */
export function expandTerms(terms: string[]): string[] {
  const out = new Set<string>();
  for (const t of terms) for (const s of synonymsOf(t)) out.add(s);
  return [...out];
}

/**
 * צירופים רב-מיליים שיש לזהות לפני פיצול למילים.
 * "תל אביב" חייב להיתפס כיחידה אחת, אחרת "תל" ו"אביב" מתפרקים.
 */
export const MULTI_WORD_TERMS: string[] = [...new Set(
  GROUPS.flat().map(normalize).filter((t) => t.includes(" ")),
)].sort((a, b) => b.length - a.length);

/** מספר קבוצות השקילות — נבדק בבדיקות כדי שהמילון לא יצטמצם בטעות. */
export const SYNONYM_TERM_COUNT = SYNONYMS.size;
