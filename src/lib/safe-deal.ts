/**
 * הרשימה לקטגוריה נתונה.
 *
 * האזהרות הכלליות תמיד אחרונות. הספציפיות למעלה מפני שהן אלה שהקונה
 * לא חשב עליהן — "אל תשלמו מראש" הוא דבר שרובם כבר יודעים.
 */
export function dealTipsFor(rootSlug: string | null | undefined): DealTip[] {
  const specific = rootSlug ? (BY_ROOT[rootSlug] ?? []) : [];
  return [...specific, ...UNIVERSAL];
}

